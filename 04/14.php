<?php

$a = "1000";
$b = "+1000";

// 不等価演算子 (!=): 緩やかな比較
// 両方が数値形式の文字列の場合、数値 (1000) に自動変換されて比較されるため false となり "1" は出力されない
if ($a != $b) {
    echo "1";
}

// 厳密不等価演算子 (!==): 厳密な比較
// 型変換を行わず、型と値そのものを比較する
// 文字列型同士だが "1000" と "+1000" で文字列の内容が異なるため true となり "2" が出力される
if ($a !== $b) {
    echo "2";
}
