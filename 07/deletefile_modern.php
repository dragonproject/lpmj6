<?php

// 厳格な型チェックモードを有効化
declare(strict_types=1);

/**
 * ==============================================================================
 * 07/deletefile_modern.php: 安全で堅牢なファイル削除処理
 * ==============================================================================
 * 
 * 元の deletefile.php にあった以下の問題点を改善したコードです：
 * 
 * 1. 【PHP Warning の防止】
 *    ファイルが存在しない状態で unlink() を実行すると PHP Warning が発生します。
 *    事前に is_file() または file_exists() で存在を確認することで警告を防ぎます。
 * 
 * 2. 【DRY原則の徹底】
 *    ファイル名を変数 ($filename) にまとめ、重複記述をなくします。
 * 
 * 3. 【PSR-12 コーディング規約に準拠】
 *    if / else の波括弧 {} を省略せず、安全で読みやすい構造にします。
 *    また、PHPのみのファイルでは末尾の「?>」を省略します。
 */

// 実行場所（カレントディレクトリ）に依存しないよう __DIR__ でパスを指定
$filename = __DIR__ . '/testfile2.new';
$displayFilename = basename($filename);

// ==============================================================================
// パターン1: 基本的かつ堅牢な条件分岐
// ==============================================================================

// 1. そもそもファイルが存在しているかを確認（ディレクトリではなく通常ファイルかを判定）
if (!is_file($filename)) {
    echo "ファイル '{$displayFilename}' は存在しません。<br>";
} elseif (unlink($filename)) {
    // 2. 正常に削除できた場合
    echo "ファイル '{$displayFilename}' を正常に削除しました。<br>";
} else {
    // 3. ファイルは存在するが、パーミッション（書き込み権限）不足などで削除失敗した場合
    echo "ファイル '{$displayFilename}' の削除に失敗しました（権限不足など）。<br>";
}


// ==============================================================================
// パターン2: 実務でよく使う「安全な削除関数」として共通化する例
// ==============================================================================

/**
 * 安全にファイルを削除するユーティリティ関数
 *
 * @param string $path 削除対象のファイルパス
 * @return bool 削除成功、または元々存在しなかった場合 true / 削除失敗時 false
 */
function safeDeleteFile(string $path): bool
{
    // ファイルが存在しない場合は、すでに削除されたとみなして安全に終了
    if (!is_file($path)) {
        return true;
    }

    // unlink が失敗したときのエラーも考慮
    return unlink($path);
}
